/**
 * scripts/build.mjs — build the software WebGL renderer bundle.
 *
 * Bundles src/entry.ts (TypeScript, zero runtime deps) into a single
 * browser-safe IIFE at ./renderer.js via esbuild. The bundle defines
 * window.__createSoftwareWebGLContext(canvas, attrs[, type]).
 *
 * Usage: npm run build   (optionally: MINIFY=1 npm run build)
 */
import { build } from 'esbuild';

const minify = process.env.MINIFY === '1';

await build({
  entryPoints: ['src/entry.ts'],
  bundle: true,
  format: 'iife',
  target: 'es2019',
  outfile: 'renderer.js',
  minify,
  sourcemap: false,
  logLevel: 'info',
  banner: {
    js: '/* webgl-bench software WebGL renderer (pure JS) — generated by scripts/build.mjs from src/. Do not edit directly. */',
  },
});

console.log(`Built renderer.js${minify ? ' (minified)' : ''} — defines window.__createSoftwareWebGLContext`);
