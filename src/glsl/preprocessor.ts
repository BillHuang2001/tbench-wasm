function initMacros(macros: Map<string, Macro>): void {
  macros.set('__LINE__', { name: '__LINE__', params: null, body: [], paramIndex: new Map(), rawArgs: [], kind: 'line' });
  macros.set('__FILE__', { name: '__FILE__', params: null, body: [], paramIndex: new Map(), rawArgs: [], kind: 'file' });
  macros.set('__VERSION__', { name: '__VERSION__', params: null, body: [], paramIndex: new Map(), rawArgs: [], kind: 'version' });
  macros.set('GL_ES', { name: 'GL_ES', params: null, body: [], paramIndex: new Map(), rawArgs: [], kind: 'gl_es' });
}

/** Tokenize a #define replacement value (used for injected `defines`). */
function charsOf(value: string): Char[] {
  const out: Char[] = [];
  let line = 1;
  for (const ch of value) {
    out.push({ ch, line });
    if (ch === '\n') line++;
  }
  return out;
}

/**
 * Run the preprocessor. Returns the expanded token stream plus the declared
 * version, enabled extensions and every #extension directive, or the list of
 * compile errors (1-based lines, after #line remapping).
 */
export function preprocess(source: string, opts: PreprocessOptions): PreprocessResult {
  const errors: CompileError[] = [];
  const st: State = {
    macros: new Map(),
    version: 100,
    lineOffset: 0,
    errors,
    extState: new Map(),
    allState: null,
    extensionDirectives: [],
    condStack: [],
    sawContent: false,
    versionSeen: false,
    opts,
  };
  initMacros(st.macros);
  if (opts.defines) {
    for (const [name, value] of Object.entries(opts.defines)) {
      if (name === 'defined') {
        errors.push({ line: 1, message: "'defined' cannot be used as a macro name" });
        continue;
      }
      const body = tokenize(charsOf(value)).filter((t) => t.text !== '\n');
      st.macros.set(name, { name, params: null, body, paramIndex: new Map(), rawArgs: [], kind: 'normal' });
    }
  }

  const tokens = tokenize(stripComments(splice(source), errors));
  const out: RawToken[] = [];
  let i = 0;
  while (i < tokens.length) {
    const t = tokens[i];
    if (t.text === '\n') {
      i++;
      continue;
    }
    const atLineStart = i === 0 || tokens[i - 1].text === '\n';
    if (t.text === '#' && atLineStart) {
      // Directive: consume the `#` plus everything up to (not incl.) the newline.
      let j = i + 1;
      while (j < tokens.length && tokens[j].text !== '\n') j++;
      const dTokens = tokens.slice(i + 1, j);
      const dline = t.line;
      i = j < tokens.length ? j + 1 : j;
      dispatchDirective(dTokens, dline, st);
      continue;
    }
    // Regular token (a `#` elsewhere is an ordinary token; the lexer validates it).
    st.sawContent = true;
    if (condActive(st)) {
      // Collect the run across newlines (function-like invocations may span
      // lines; `\n` tokens are whitespace to expansion and filtered below).
      const run: PToken[] = [];
      while (i < tokens.length) {
        const u = tokens[i];
        const uDir = u.text === '#' && (i === 0 || tokens[i - 1].text === '\n');
        if (uDir) break;
        run.push(u);
        i++;
      }
      const expanded = expandTokens(run, null, st);
      for (const e of expanded) {
        if (e.text === '\n') continue;
        out.push({ text: e.text, line: remap(st, e.line), column: e.column });
      }
    } else {
      // Skipped branch: consume without expansion, produce no tokens.
      while (i < tokens.length) {
        const u = tokens[i];
        if (u.text === '\n') break;
        const uDir = u.text === '#' && (i === 0 || tokens[i - 1].text === '\n');
        if (uDir) break;
        i++;
      }
    }
  }

  for (const f of st.condStack) {
    errors.push({ line: f.line, message: 'unterminated #if (missing #endif)' });
  }
  if (errors.length > 0) return { ok: false, errors };

  const extensions: string[] = [];
  for (const [name, beh] of st.extState) {
    if (beh === 'enable' || beh === 'require') extensions.push(name);
  }
  return { ok: true, tokens: out, version: st.version, extensions, extensionDirectives: st.extensionDirectives };
}
