const IDENT_RE = /^[A-Za-z_][A-Za-z0-9_]*$/;
const isIdent = (s: string): boolean => IDENT_RE.test(s);
const isDigit = (c: string): boolean => c >= '0' && c <= '9';
const isHexDigit = (c: string): boolean => (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F');
const isIdentStart = (c: string): boolean => (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || c === '_';
const isIdentChar = (c: string): boolean => isIdentStart(c) || isDigit(c);
const isSpace = (c: string): boolean => c === ' ' || c === '\t' || c === '\r' || c === '\v' || c === '\f';
/** Number suffix letters (uint/float suffixes are consumed greedily). */
const isSuffix = (c: string): boolean => c === 'u' || c === 'U' || c === 'f' || c === 'F';

const remap = (st: State, line: number): number => line + st.lineOffset;

function condActive(st: State): boolean {
  return st.condStack.length === 0 || st.condStack[st.condStack.length - 1].active;
}

function addHidden(h: Set<string> | null, name: string): Set<string> {
  const s = h ? new Set(h) : new Set<string>();
  s.add(name);
  return s;
}

function unionHidden(a: Set<string> | null, b: Set<string> | null): Set<string> | null {
  if (!a && !b) return null;
  const s = new Set<string>();
  if (a) for (const x of a) s.add(x);
  if (b) for (const x of b) s.add(x);
  return s;
}

const hasHidden = (t: PToken, name: string): boolean => t.hidden !== null && t.hidden.has(name);

/** Mark `##` tokens in a replacement list as paste operators. */
function markPastes(tokens: PToken[]): PToken[] {
  return tokens.map((t) => (t.text === '##' ? { ...t, paste: true } : t));
}

/** Perform the token-paste pass over a substituted replacement list. */
function pasteTokens(out: PToken[]): PToken[] {
  const res: PToken[] = [];
  for (let i = 0; i < out.length; i++) {
    const t = out[i];
    if (!t.paste) {
      res.push(t);
      continue;
    }
    // `##`: paste the next non-marker token onto the previous result.
    let j = i + 1;
    while (j < out.length && out[j].paste) j++;
    if (j >= out.length) break; // trailing ##: dropped (permissive)
    const right = out[j];
    if (res.length > 0) {
      const left = res[res.length - 1];
      res[res.length - 1] = {
        text: left.text + right.text,
        line: left.line,
        column: left.column,
        ws: left.ws,
        hidden: unionHidden(left.hidden, right.hidden),
      };
    } else {
      res.push({ ...right }); // leading ##: nothing to paste onto (permissive)
    }
    i = j;
  }
  return res;
}

/** Re-tag replacement tokens with the invocation site position (__LINE__ etc. use it). */
function retag(body: PToken[], inv: PToken): PToken[] {
  return body.map((b) => ({ ...b, line: inv.line, column: inv.column }));
}

/** `#x` stringize: argument tokens → one string-literal token. */
function stringize(arg: PToken[], inv: PToken): PToken {
  let s = '';
  for (let i = 0; i < arg.length; i++) {
    if (i > 0) s += ' ';
    s += arg[i].text;
  }
  s = s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  return { text: '"' + s + '"', line: inv.line, column: inv.column, ws: false, hidden: null };
}

// ------------------------------------------------------------------
// Phase 1: line splicing
// ------------------------------------------------------------------

/**
 * Splice backslash-newline (and backslash-\r\n / backslash-\r) pairs BEFORE
 * comment and directive processing, per C phase 2 / GLSL ES sec. 3.4. `\r` and
 * `\r\n` are normalized to `\n`. Every char keeps its physical line number.
 */
function splice(source: string): Char[] {
  const out: Char[] = [];
  let line = 1;
  let i = 0;
  const n = source.length;
  while (i < n) {
    const c = source[i];
    if (c === '\\') {
      const next = source[i + 1];
      if (next === '\n') {
        // Splice: the continuation is part of the SAME logical line, so the
        // physical line counter does not advance (per GLSL ES §3.4 / C phase 2).
        i += 2;
        continue;
      }
      if (next === '\r') {
        if (source[i + 2] === '\n') {
          i += 3;
          continue;
        }
        i += 2;
        continue;
      }
    }
    if (c === '\r') {
      if (source[i + 1] === '\n') {
        out.push({ ch: '\n', line });
        i += 2;
        line++;
        continue;
      }
      out.push({ ch: '\n', line });
      i++;
      line++;
      continue;
    }
    if (c === '\n') {
      out.push({ ch: '\n', line });
      i++;
      line++;
      continue;
    }
    out.push({ ch: c, line });
    i++;
  }
  return out;
}

// ------------------------------------------------------------------
// Phase 2: comment stripping
// ------------------------------------------------------------------

/**
 * Replace `//` comments (to end of line) with nothing and block comments
 * with a single space (newlines inside block comments are retained so line
 * structure is preserved). An unterminated block comment is an error.
 */
function stripComments(chars: Char[], errors: CompileError[]): Char[] {
  const out: Char[] = [];
  let i = 0;
  const n = chars.length;
  while (i < n) {
    const c = chars[i];
    if (c.ch === '/' && i + 1 < n && chars[i + 1].ch === '/') {
      while (i < n && chars[i].ch !== '\n') i++;
      continue;
    }
    if (c.ch === '/' && i + 1 < n && chars[i + 1].ch === '*') {
      const startLine = c.line;
      i += 2;
      let closed = false;
      while (i < n) {
        if (chars[i].ch === '*' && i + 1 < n && chars[i + 1].ch === '/') {
          i += 2;
          closed = true;
          break;
        }
        if (chars[i].ch === '\n') {
          out.push(chars[i]);
          i++;
          continue;
        }
        i++;
      }
      if (!closed) {
        errors.push({ line: startLine, message: 'unterminated comment' });
        continue;
      }
      out.push({ ch: ' ', line: startLine });
      continue;
    }
    out.push(chars[i]);
    i++;
  }
  return out;
}

// ------------------------------------------------------------------
// Phase 3: tokenization
// ------------------------------------------------------------------

const PUNCT3: ReadonlySet<string> = new Set(['<<=', '>>=']);
const PUNCT2: ReadonlySet<string> = new Set([
  '<<', '>>', '&&', '||', '==', '!=', '<=', '>=', '^^',
  '+=', '-=', '*=', '/=', '%=', '&=', '|=', '^=', '++', '--', '##',
]);

/** Scan a number literal (dec/oct/hex, float, exponent, u/f suffix). */
function scanNumber(chars: Char[], i: number): { text: string; next: number } {
  let j = i;
  const n = chars.length;
  if (chars[j].ch === '0' && j + 1 < n && (chars[j + 1].ch === 'x' || chars[j + 1].ch === 'X')) {
    j += 2;
    while (j < n && isHexDigit(chars[j].ch)) j++;
    while (j < n && isSuffix(chars[j].ch)) j++;
    return { text: chars.slice(i, j).map((x) => x.ch).join(''), next: j };
  }
  while (j < n && isDigit(chars[j].ch)) j++;
  if (j < n && chars[j].ch === '.') {
    j++;
    while (j < n && isDigit(chars[j].ch)) j++;
  }
  if (j < n && (chars[j].ch === 'e' || chars[j].ch === 'E')) {
    let k = j + 1;
    if (k < n && (chars[k].ch === '+' || chars[k].ch === '-')) k++;
    if (k < n && isDigit(chars[k].ch)) {
      j = k;
      while (j < n && isDigit(chars[j].ch)) j++;
    }
  }
  while (j < n && isSuffix(chars[j].ch)) j++;
  return { text: chars.slice(i, j).map((x) => x.ch).join(''), next: j };
}

/**
 * Tokenize the cleaned stream. Whitespace is dropped; newlines are kept as
 * `\n` tokens (directive detection needs line boundaries); every other run of
 * characters becomes a token (identifiers, numbers, punctuators, single
 * chars — `"` is a single-char token; the lexer validates characters later).
 */
function tokenize(chars: Char[]): PToken[] {
  const out: PToken[] = [];
  let i = 0;
  let col = 0;
  let lastEnd = 0; // index in chars just past the previous token (ws detection)
  const n = chars.length;
  while (i < n) {
    const c = chars[i];
    if (c.ch === '\n') {
      out.push({ text: '\n', line: c.line, column: 0, ws: false, hidden: null });
      i++;
      col = 0;
      continue;
    }
    if (isSpace(c.ch)) {
      i++;
      col++;
      continue;
    }
    const start = i;
    const ws = start !== lastEnd;
    let text: string;
    if (isIdentStart(c.ch)) {
      let j = i + 1;
      while (j < n && isIdentChar(chars[j].ch)) j++;
      text = chars.slice(i, j).map((x) => x.ch).join('');
      i = j;
    } else if (isDigit(c.ch) || (c.ch === '.' && i + 1 < n && isDigit(chars[i + 1].ch))) {
      const r = scanNumber(chars, i);
      text = r.text;
      i = r.next;
    } else if (c.ch === '"') {
      // String literal: ONE token (so stringize/#error preserve it verbatim).
      // Backslash escapes do not close the literal; an unterminated literal
      // runs to the end of the line (the lexer validates it later).
      let j = i + 1;
      while (j < n && chars[j].ch !== '\n') {
        if (chars[j].ch === '\\' && j + 1 < n && chars[j + 1].ch !== '\n') {
          j += 2;
          continue;
        }
        if (chars[j].ch === '"') break;
        j++;
      }
      if (j < n && chars[j].ch === '"') j++;
      text = chars.slice(i, j).map((x) => x.ch).join('');
      i = j;
    } else {
      const two = c.ch + (i + 1 < n ? chars[i + 1].ch : '');
      const three = two + (i + 2 < n ? chars[i + 2].ch : '');
      if (PUNCT3.has(three)) {
        text = three;
        i += 3;
      } else if (PUNCT2.has(two)) {
        text = two;
        i += 2;
      } else {
        text = c.ch;
        i += 1;
      }
    }
    out.push({ text, line: c.line, column: col, ws, hidden: null });
    col += i - start;
    lastEnd = i;
  }
  return out;
}

// ------------------------------------------------------------------
// Phase 4: macro expansion
// ------------------------------------------------------------------

/**
 * Fully expand a token list (queue-splice algorithm with per-token hide
 * sets). A function-like macro is invoked only when the `(` immediately
 * follows the name (no whitespace); args are parsed with balanced parens
 * (they may span lines); each argument is pre-expanded EXCEPT when adjacent
 * to `#`/`##`; the substituted replacement list is re-scanned together with
 * the remaining input tokens — which is what makes `#define A B` +
 * `#define B(x) x` + `A(1)` expand to `1`.
 */
function expandTokens(list: PToken[], baseHidden: Set<string> | null, st: State): PToken[] {
  const queue: PToken[] = list.map((t) => ({ ...t, hidden: t.hidden ?? baseHidden ?? null }));
  const out: PToken[] = [];
  let i = 0;
  while (i < queue.length) {
    const t = queue[i];
    const m = isIdent(t.text) && !hasHidden(t, t.text) ? st.macros.get(t.text) : undefined;
    if (!m) {
      out.push(t);
      i++;
      continue;
    }
    if (m.params === null) {
      // Object-like macro.
      if (m.kind !== 'normal') {
        // Predefined dynamic macro: __LINE__ / __FILE__ / __VERSION__ / GL_ES.
        const text =
          m.kind === 'line' ? String(remap(st, t.line)) :
          m.kind === 'file' ? '0' :
          m.kind === 'version' ? String(st.version) :
          '1';
        queue.splice(i, 1, { text, line: t.line, column: t.column, ws: t.ws, hidden: t.hidden });
        continue;
      }
      const hidden = addHidden(t.hidden, t.text);
      const body = pasteTokens(markPastes(retag(m.body, t))).map((b) => ({ ...b, hidden }));
      queue.splice(i, 1, ...body);
      continue;
    }
    // Function-like macro: requires `(` immediately following (no whitespace).
    const next = queue[i + 1];
    if (next && next.text === '(' && !next.ws) {
      let depth = 1;
      let k = i + 2;
      const args: PToken[][] = [];
      let cur: PToken[] = [];
      let end = -1;
      let sawComma = false; // `F()` is zero args; `G(,)` is two empty args
      while (k < queue.length) {
        const u = queue[k];
        if (u.text === '\n') {
          // Newlines inside an argument list are whitespace (C phase 3: the
          // invocation continues across lines until the matching `)`).
          k++;
          continue;
        }
        if (u.text === '(') {
          depth++;
          cur.push(u);
          k++;
          continue;
        }
        if (u.text === ')') {
          depth--;
          if (depth === 0) {
            // `()` is ZERO arguments for a 0-parameter macro (`F()` → 42) but
            // ONE empty argument otherwise (`STR()` → `""`, per cpp/C11).
            if (sawComma || cur.length > 0 || m.params.length > 0) args.push(cur);
            end = k;
            break;
          }
          cur.push(u);
          k++;
          continue;
        }
        if (depth === 1 && u.text === ',') {
          args.push(cur);
          cur = [];
          sawComma = true;
          k++;
          continue;
        }
        cur.push(u);
        k++;
      }
      if (end < 0) {
        st.errors.push({ line: remap(st, t.line), message: `unterminated invocation of macro '${t.text}'` });
        out.push(t);
        i++;
        continue;
      }
      if (args.length !== m.params.length) {
        st.errors.push({
          line: remap(st, t.line),
          message: `macro '${t.text}' requires ${m.params.length} argument(s), but ${args.length} given`,
        });
        out.push(t);
        i++;
        continue;
      }
      const hidden = addHidden(t.hidden, t.text);
      // C99 6.10.3.1: argument pre-expansion happens with the CURRENT hide set
      // (the one the arg tokens carry at the invocation site) — the macro being
      // expanded is NOT hidden here; it is hidden only during the re-scan of
      // its own replacement text below.
      const expandedArgs = args.map((arg, ai) => (m.rawArgs[ai] ? arg : expandTokens(arg, null, st)));
      const body = substitute(m, expandedArgs, hidden, t);
      queue.splice(i, end - i + 1, ...body);
      continue;
    }
    out.push(t);
    i++;
  }
  return out;
}

/**
 * Substitute arguments into a function-like macro body: replace parameters
 * (expanded or raw per adjacency), handle `#` stringize and `##` paste, then
 * re-tag body tokens with the invocation position and hide set.
 */
function substitute(m: Macro, args: PToken[][], hidden: Set<string> | null, inv: PToken): PToken[] {
  const body = m.body;
  const out: PToken[] = [];
  for (let i = 0; i < body.length; i++) {
    const t = body[i];
    if (t.text === '#' && i + 1 < body.length) {
      const idx = m.paramIndex.get(body[i + 1].text);
      if (idx !== undefined) {
        out.push(stringize(args[idx], inv));
        i++;
        continue;
      }
      out.push({ ...t, line: inv.line, column: inv.column, hidden });
      continue;
    }
    if (t.text === '##') {
      out.push({ ...t, line: inv.line, column: inv.column, paste: true, hidden });
      continue;
    }
    const idx = m.paramIndex.get(t.text);
    if (idx !== undefined) {
      out.push(...args[idx]);
      continue;
    }
    out.push({ ...t, line: inv.line, column: inv.column, hidden });
  }
  return pasteTokens(out);
}

