/** Parse an integer literal: hex, octal (permissive), decimal; u/f suffix stripped. */
function parseIntLiteral(text: string): number {
  const m = /^(0[xX][0-9a-fA-F]+|[0-9]+)([uUfF]*)$/.exec(text);
  if (!m) return 0;
  const body = m[1];
  if (body.length > 1 && body[0] === '0') {
    if (body[1] === 'x' || body[1] === 'X') {
      const v = parseInt(body.slice(2), 16);
      return Number.isNaN(v) ? 0 : v;
    }
    if (/^0[0-7]+$/.test(body)) return parseInt(body, 8);
  }
  const v = parseInt(body, 10);
  return Number.isNaN(v) ? 0 : v;
}

/** Replace `defined NAME` / `defined(NAME)` with 1/0 BEFORE macro expansion. */
function handleDefined(tokens: PToken[], st: State): PToken[] {
  const out: PToken[] = [];
  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i];
    if (t.text !== 'defined') {
      out.push(t);
      continue;
    }
    const next = tokens[i + 1];
    if (next && next.text === '(') {
      const id = tokens[i + 2];
      const close = tokens[i + 3];
      if (id && isIdent(id.text) && close && close.text === ')') {
        out.push({ text: st.macros.has(id.text) ? '1' : '0', line: t.line, column: t.column, ws: false, hidden: null });
        i += 3;
        continue;
      }
    } else if (next && isIdent(next.text)) {
      out.push({ text: st.macros.has(next.text) ? '1' : '0', line: t.line, column: t.column, ws: false, hidden: null });
      i += 1;
      continue;
    }
    // Malformed `defined` — left in place; the post-expansion check errors.
    out.push(t);
  }
  return out;
}

const BINOP: Record<string, { prec: number; fn: (a: number, b: number) => number }> = {
  '||': { prec: 1, fn: (a, b) => (a !== 0 || b !== 0 ? 1 : 0) },
  '&&': { prec: 2, fn: (a, b) => (a !== 0 && b !== 0 ? 1 : 0) },
  '|': { prec: 3, fn: (a, b) => (a | b) >>> 0 },
  '^': { prec: 4, fn: (a, b) => (a ^ b) >>> 0 },
  '&': { prec: 5, fn: (a, b) => (a & b) >>> 0 },
  '==': { prec: 6, fn: (a, b) => (a === b ? 1 : 0) },
  '!=': { prec: 6, fn: (a, b) => (a !== b ? 1 : 0) },
  '<': { prec: 7, fn: (a, b) => (a < b ? 1 : 0) },
  '>': { prec: 7, fn: (a, b) => (a > b ? 1 : 0) },
  '<=': { prec: 7, fn: (a, b) => (a <= b ? 1 : 0) },
  '>=': { prec: 7, fn: (a, b) => (a >= b ? 1 : 0) },
  '<<': { prec: 8, fn: (a, b) => a << b },
  '>>': { prec: 8, fn: (a, b) => a >> b },
  '+': { prec: 9, fn: (a, b) => a + b },
  '-': { prec: 9, fn: (a, b) => a - b },
  '*': { prec: 10, fn: (a, b) => a * b },
  '/': { prec: 10, fn: (a, b) => (b === 0 ? 0 : Math.trunc(a / b)) },
  '%': { prec: 10, fn: (a, b) => (b === 0 ? 0 : a % b) },
};

/** Recursive-descent (precedence climbing) parser for #if/#elif expressions. */
class ExprParser {
  private i = 0;
  private failed = false;
  /** When set, parse errors are suppressed (short-circuited && / || rhs). */
  private quiet = false;

  constructor(private readonly tokens: PToken[], private readonly st: State, private readonly line: number) {}

  parse(): number {
    const v = this.parseExpr(1);
    if (!this.failed && this.i < this.tokens.length) this.err();
    return this.failed ? 0 : v;
  }

  private err(): void {
    if (this.failed || this.quiet) return;
    this.failed = true;
    this.st.errors.push({ line: remap(this.st, this.line), message: 'invalid expression in #if' });
  }

  private peek(text: string): boolean {
    const t = this.tokens[this.i];
    return t !== undefined && t.text === text;
  }

  private parseExpr(minPrec: number): number {
    let v = this.parseUnary();
    for (;;) {
      const t = this.tokens[this.i];
      if (!t) break;
      const op = BINOP[t.text];
      if (!op || op.prec < minPrec) break;
      this.i++;
      if (op.prec === 1 || op.prec === 2) {
        // Short-circuit `||` (prec 1) and `&&` (prec 2): the right side is not
        // evaluated. It is still consumed so the parse position stays correct,
        // but errors inside it (e.g. undefined identifiers, 1/0) are ignored.
        if (op.prec === 1 ? v !== 0 : v === 0) {
          const saved = this.quiet;
          this.quiet = true;
          this.parseExpr(op.prec + 1);
          this.quiet = saved;
          v = op.prec === 1 ? 1 : 0;
        } else {
          v = op.fn(v, this.parseExpr(op.prec + 1));
        }
        continue;
      }
      v = op.fn(v, this.parseExpr(op.prec + 1));
    }
    return v;
  }

  private parseUnary(): number {
    if (this.peek('!')) {
      this.i++;
      return this.parseUnary() === 0 ? 1 : 0;
    }
    if (this.peek('~')) {
      this.i++;
      return ~this.parseUnary();
    }
    if (this.peek('+')) {
      this.i++;
      return this.parseUnary();
    }
    if (this.peek('-')) {
      this.i++;
      return -this.parseUnary();
    }
    return this.parsePrimary();
  }

  private parsePrimary(): number {
    const t = this.tokens[this.i];
    if (t === undefined) {
      this.err();
      return 0;
    }
    if (t.text === '(') {
      this.i++;
      const v = this.parseExpr(1);
      if (!this.peek(')')) {
        this.err();
        return 0;
      }
      this.i++;
      return v;
    }
    if (isDigit(t.text[0]) || (t.text[0] === '.' && t.text.length > 1)) {
      this.i++;
      return parseIntLiteral(t.text);
    }
    if (isIdent(t.text)) {
      this.i++;
      // GLSL ES §3.4: any identifier remaining after macro expansion that is
      // not a defined macro is UNDEFINED, and an undefined identifier in an
      // #if expression is an ERROR (unlike C, which substitutes 0). CTS:
      // conformance/glsl/misc/shader-with-undefined-preprocessor-symbol.frag.html.
      this.err();
      return 0;
    }
    this.err();
    return 0;
  }
}

/** Evaluate the #if/#elif condition tokens. */
function evalCondition(tokens: PToken[], line: number, st: State): number {
  if (tokens.length === 0) {
    st.errors.push({ line: remap(st, line), message: 'invalid expression in #if' });
    return 0;
  }
  const handled = handleDefined(tokens, st);
  const expanded = expandTokens(handled, null, st);
  for (const t of expanded) {
    if (t.text === 'defined') {
      // WebGL requirement: `defined` generated by macro replacement is an error.
      st.errors.push({ line: remap(st, line), message: "'defined' generated by macro expansion in #if" });
      return 0;
    }
  }
  return new ExprParser(expanded, st, line).parse();
}

