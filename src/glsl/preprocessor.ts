/**
 * preprocessor.ts — the GLSL ES 1.00 / 3.00 preprocessor stage (spec §3.4).
 *
 * Pipeline position: `compileShader` runs preprocessor → lexer → parser →
 * semantics. This module consumes the raw shader source and emits a flat token
 * stream (RawToken[]) with every directive processed and every macro expanded,
 * plus the declared `#version`, the final extension state and every
 * `#extension` directive (the parser later converts those into ExtensionDecl
 * AST nodes). It performs no syntax validation of shader code — characters the
 * lexer rejects (e.g. `@`) pass through as single-char tokens.
 *
 * C-preprocessor semantics (GLSL ES inherits the C model): backslash-newline
 * line splicing; `//` and block-comment stripping (no nesting; newlines inside
 * block comments retained); object-like and function-like macros with `#`
 * stringize and `##` token paste; argument pre-expansion except adjacent to
 * `#`/`##`; full re-scan with recursion suppression via per-token hide sets
 * (A→B, B→A terminates); predefined macros __LINE__/__FILE__/__VERSION__/
 * GL_ES; `#extension` macros (enable/require define the name = 1, disable
 * removes it, warn defines nothing; `all` works with warn/disable only);
 * `#if`/`#elif`/`#ifdef`/`#ifndef`/`#else`/`#endif` with full integer constant
 * expression evaluation (`defined(NAME)` / `defined NAME`, C precedence,
 * 32-bit shifts, division by zero → 0, undefined identifiers → error per
 * GLSL ES §3.4); skipped branches are consumed but never expanded (directive
 * lines inside an inactive group are ignored entirely); `#error`; `#pragma`
 * (ignored); `#version` (exactly one); `#line` (1-arg in ESSL 1.00, optional
 * integer source-string-number in 3.00; the line following the directive
 * becomes the number).
 * WebGL requirements: `defined` may not be used as a macro name, and a
 * `defined` token generated by macro expansion inside `#if` is an error.
 *
 * Errors: 1-based lines (after `#line` remapping), Khronos-style free-form
 * messages; all errors are collected and processing continues where possible.
 */
import type { CompileError } from './compiler.js';

// ------------------------------------------------------------------
// Public interface (consumed by the lexer stage)
// ------------------------------------------------------------------

export interface RawToken {
  /** Raw token text (identifier, number, punctuator, string literal...). */
  text: string;
  /** 1-based line AFTER #line remapping. */
  line: number;
  /** 0-based column within the line. */
  column: number;
}

export type ExtensionBehavior = 'require' | 'enable' | 'warn' | 'disable';

export interface ExtensionDirective {
  name: string;
  behavior: ExtensionBehavior;
  line: number;
}

export type PreprocessResult =
  | { ok: true; tokens: RawToken[]; version: 100 | 300; extensions: string[]; extensionDirectives: ExtensionDirective[] }
  | { ok: false; errors: CompileError[] };

export interface PreprocessOptions {
  /** Highest GLSL version the CONTEXT supports (100 = WebGL1, 300 = WebGL2). */
  version: 100 | 300;
  /** Extra preprocessor defines injected before the source (object-like). */
  defines?: Record<string, string>;
  /** Extensions the context supports; `#extension X : require|enable` of an unsupported name is an error. */
  extensions?: Set<string>;
}

// ------------------------------------------------------------------
// Internal model
// ------------------------------------------------------------------

/** A char of the spliced, comment-stripped stream with its physical line. */
interface Char {
  ch: string;
  line: number;
}

/**
 * Internal preprocessor token: source position plus `ws` (preceded by
 * whitespace — prevents function-like invocation) and `hidden` (macro names
 * suppressed from re-expansion, the C "hide set" that makes A→B, B→A
 * terminate).
 */
interface PToken {
  text: string;
  line: number;
  column: number;
  ws: boolean;
  hidden: Set<string> | null;
  /** Token-paste operator marker (only inside macro replacement lists). */
  paste?: boolean;
}

interface Macro {
  name: string;
  /** null = object-like macro; otherwise the parameter names. */
  params: string[] | null;
  /** Replacement-list tokens (from the #define line; raw, unexpanded). */
  body: PToken[];
  paramIndex: Map<string, number>;
  /** Per-parameter: true when adjacent to `#`/`##` (argument NOT pre-expanded). */
  rawArgs: boolean[];
  /** Predefined dynamic macros expand to a computed number. */
  kind: 'normal' | 'line' | 'file' | 'version' | 'gl_es';
}

interface CondFrame {
  parentActive: boolean;
  taken: boolean;
  active: boolean;
  elseSeen: boolean;
  /** Remapped line of the #if (reported for unterminated conditionals). */
  line: number;
}

/** Mutable state threaded through directive handling and expansion. */
interface State {
  macros: Map<string, Macro>;
  version: 100 | 300;
  lineOffset: number;
  errors: CompileError[];
  extState: Map<string, ExtensionBehavior>;
  allState: ExtensionBehavior | null;
  extensionDirectives: ExtensionDirective[];
  condStack: CondFrame[];
  /** Any token or non-#version directive seen before #version (spec: #version must be first). */
  sawContent: boolean;
  /** A #version directive has already been processed (spec: at most one). */
  versionSeen: boolean;
  opts: PreprocessOptions;
}

